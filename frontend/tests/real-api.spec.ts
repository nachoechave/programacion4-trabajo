import { test, expect } from '@playwright/test';
test('Rails real: login, persistencia, error y logout', async ({page})=>{
  test.skip(process.env['REAL_API'] !== '1', 'Requiere Rails y PostgreSQL de pruebas');
  const code='CI-'+Date.now();
  await page.goto('/');
  await page.getByLabel('Correo electrónico').fill('admin@example.com');
  await page.getByLabel('Contraseña').fill('password123');
  await page.getByRole('button',{name:/Iniciar sesión/}).click();
  await expect(page.getByText('Administrador',{exact:false}).first()).toBeVisible();
  await page.getByRole('button',{name:/Investigaciones/}).click();
  await page.getByRole('button',{name:/Nuevo caso/}).click();
  await page.getByLabel('Código *').fill(code);
  await page.getByLabel('Título *').fill('Caso integrado CI');
  await page.getByRole('button',{name:'Guardar investigación'}).click();
  await expect(page.getByText('Caso registrado correctamente en PostgreSQL.')).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:/Investigaciones/}).click();
  await expect(page.getByText(code,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Nuevo caso/}).click();
  await page.getByLabel('Código *').fill(code);
  await page.getByLabel('Título *').fill('Duplicado');
  const rejected=page.waitForResponse(r=>r.url().endsWith('/api/v1/cases')&&r.request().method()==='POST'&&r.status()===422);
  await page.getByRole('button',{name:'Guardar investigación'}).click();
  await rejected;
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByRole('button',{name:/Evidencias/}).click();
  await page.getByRole('button',{name:/Ver historial/}).first().click();
  await expect(page.getByRole('heading',{name:'Historial inmutable de movimientos'})).toBeVisible();
  await page.getByRole('button',{name:/Cerrar sesión/}).click();
  await expect(page.getByRole('heading',{name:'Bienvenido'})).toBeVisible();
});
